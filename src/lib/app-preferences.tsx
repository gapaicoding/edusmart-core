/** Translate exact shared UI labels only; values and domain identifiers are untouched. */
export function translateUiText(value: string, locale: Locale) {
  if (locale === "en") return value;
  const periodLabel = /^Period\s+(\d+)$/i.exec(value);
  if (periodLabel) return `Periode ${periodLabel[1]}`;
  const statusKey = `common.status.${value.toLowerCase()}`;
  if (statusKey in messages.id) return messages.id[statusKey as keyof typeof messages.id];
  return sharedCopy[value] ?? extendedSharedCopy[value] ?? value;
}

export function translateUiNode(node: ReactNode, locale: Locale): ReactNode {
  if (typeof node === "string") return translateUiText(node, locale);
  if (Array.isArray(node))
    return node.map((child, index) => {
      const translated = translateUiNode(child, locale);
      return isValidElement(translated) && translated.key === null
        ? cloneElement(translated, { key: `localized-copy-${index}` })
        : translated;
    });
  if (isValidElement<{ children?: ReactNode }>(node) && node.props.children !== undefined)
    return cloneElement(node, {
      children: translateUiNode(node.props.children, locale),
    });
  return node;
}

