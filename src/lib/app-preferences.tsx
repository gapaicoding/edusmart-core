function isLocale(value: string | null): value is Locale {
  return value === "id" || value === "en";
}

function isTheme(value: string | null): value is Theme {
  return value === "light" || value === "dark";
}

export function AppPreferencesProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("id");
  const [theme, setThemeState] = useState<Theme>("light");

  useEffect(() => {
    const storedLocale = window.localStorage.getItem(LOCALE_KEY);
    const storedTheme = window.localStorage.getItem(THEME_KEY);
    if (isLocale(storedLocale)) setLocaleState(storedLocale);
    if (isTheme(storedTheme)) setThemeState(storedTheme);
  }, []);

  useEffect(() => {
    window.localStorage.setItem(LOCALE_KEY, locale);
    document.documentElement.lang = locale === "id" ? "id" : "en";
  }, [locale]);

  useEffect(() => {
    window.localStorage.setItem(THEME_KEY, theme);
    document.documentElement.classList.toggle("dark", theme === "dark");
    document.documentElement.style.colorScheme = theme;
  }, [theme]);

  const value = useMemo<PreferencesContextValue>(() => {
    const language = locale === "id" ? "id-ID" : "en-US";
    return {
      locale,
      theme,
      setLocale: (next) => setLocaleState(next),
      setTheme: (next) => setThemeState(next),
      t: (key, values) => {
        const message = String(messages[locale][key] ?? messages.en[key] ?? key);
        return values
          ? Object.entries(values).reduce<string>(
              (result, [name, value]) => result.replaceAll(`{${name}}`, value),
              message,
            )
          : message;
      },
      formatDate: (value, options) =>
        new Intl.DateTimeFormat(language, options).format(new Date(value)),
      formatNumber: (value, options) => new Intl.NumberFormat(language, options).format(value),
    };
  }, [locale, theme]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function useAppPreferences() {
  const context = useContext(PreferencesContext);
  if (!context) throw new Error("useAppPreferences must be used inside AppPreferencesProvider");
  return context;
}

