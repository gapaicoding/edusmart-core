/** Format presentation values using the active document locale, safely during SSR. */
export function formatPreferredDate(
  value: string | number | Date,
  options?: Intl.DateTimeFormatOptions,
  locale?: Locale,
) {
  const activeLocale =
    locale ??
    (typeof document !== "undefined" && document.documentElement.lang === "en" ? "en" : "id");
  const language = activeLocale === "en" ? "en-US" : "id-ID";
  return new Intl.DateTimeFormat(language, options).format(new Date(value));
}

export function formatPreferredNumber(
  value: number,
  options?: Intl.NumberFormatOptions,
  locale?: Locale,
) {
  const activeLocale =
    locale ??
    (typeof document !== "undefined" && document.documentElement.lang === "en" ? "en" : "id");
  const language = activeLocale === "en" ? "en-US" : "id-ID";
  return new Intl.NumberFormat(language, options).format(value);
}
